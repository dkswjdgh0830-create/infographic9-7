# Equal-count samples for fair comparison: all 7,908 pressured passes + 7,908 random unpressured (seed fixed).
import csv, random, sys
rows=[r for r in csv.DictReader(open(sys.argv[1],encoding='utf-8-sig')) if r['excluded_set_piece_restart']=='False']
D={'전진':0,'횡':1,'후방':2}
P=[r for r in rows if r['under_pressure']=='1']
N=[r for r in rows if r['under_pressure']=='0']
random.seed(2022); N=random.sample(N,len(P)); N.sort(key=lambda r:(r['match_id'],int(r['period']),int(r['minute']),int(r['second'])))
def enc(rs):  # x1,y1,x2,y2 in 0.1yd, dir, success(-1 = not evaluated)
    out=[]
    for r in rs:
        s=int(r['pass_success']) if r['included_in_success_rate']=='True' else -1
        out+= [round(float(r[k])*10) for k in ('start_x','start_y','end_x','end_y')]+[D[r['pass_direction']],s]
    return ','.join(map(str,out))
open('passes.js','w',encoding='utf-8').write(
 '// generated by tools/build_data.py from wc2022_passes_events.csv (open play, StatsBomb 120x80yd, attack → +x)\n'
 f'const PASS_N=[{enc(N)}];\nconst PASS_P=[{enc(P)}];\n')
print(len(P),len(N))
